// Draw n cards (optionally reversed) from the full 78-card deck.
export function drawTarot(n = 3, seed) {
  const deck = [...TAROT_DECK];
  let rng;
  if (seed != null) {
    // simple deterministic LCG so the same seed → same draw (mirrors backend)
    let s = seed % 2147483647;
    if (s <= 0) s += 2147483646;
    rng = () => (s = (s * 16807) % 2147483647) / 2147483647;
  } else {
    rng = Math.random;
  }
  const out = [];
  for (let i = 0; i < n && deck.length; i++) {
    const idx = Math.floor(rng() * deck.length);
    const card = deck.splice(idx, 1)[0];
    out.push({ ...card, reversed: rng() < 0.5 });
  }
  return out;
}
