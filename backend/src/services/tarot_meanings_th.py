def th_card_name(card_name: str) -> str:
    """Beautiful classical-Thai name for any tarot card (Major or Minor)."""
    if card_name in THAI_CARD_NAMES:
        return THAI_CARD_NAMES[card_name]
    import re
    m = re.match(r"^(.+?) of (.+)$", card_name)
    if m:
        rank, suit = m.group(1), m.group(2)
        r = THAI_CARD_NAMES.get(rank, rank)
        s = THAI_CARD_NAMES.get(suit, suit)
        return f"{r}แห่ง{s}"
    return card_name


def th_card_meaning(card_name: str, orientation: str = "upright") -> str:
    """Pure-Thai meaning for a card (upright/reversed). Falls back to the
    card name if no entry exists. Strips any residual latin via sanitize."""
    entry = TAROT_MEANINGS_TH.get(card_name)
    if not entry:
        return th_card_name(card_name)
    key = "reversed" if orientation == "reversed" else "upright"
    text = entry.get(key, entry.get("upright", ""))
    # keep only the leading Thai portion (some entries have EN fragments)
    import re
    th = re.split(r"[A-Za-z]{2,}", text)[0].strip()
    return th or text.strip()


